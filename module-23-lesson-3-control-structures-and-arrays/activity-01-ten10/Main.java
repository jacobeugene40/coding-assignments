class Main {
  public static void main(String[] args) {
    // using for loop: 10 down to 1
    for (int i = 10; i >= 1; i--) {
      System.out.println("The value of i is: " + i);
    }

    // using while loop: 1 up to 10
    int j = 1;
    while (j <= 10) {
      System.out.println("The value of j is: " + j);
      j++;
    }
  }
}
